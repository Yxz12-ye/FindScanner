"""Convert the app's monochrome SVG artwork into tintable Android vectors.

Run from any directory with: python tools/generate_ui_icons.py
The supplied Lucide artwork uses paths, circles, lines and rounded rectangles.
"""

from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "app/artwork/icons"
OUTPUT = ROOT / "app/src/main/res/drawable"
ANDROID = "http://schemas.android.com/apk/res/android"
ET.register_namespace("android", ANDROID)


def attr(name):
    return f"{{{ANDROID}}}{name}"


def path_data(element):
    tag = element.tag.rsplit("}", 1)[-1]
    if tag == "path":
        return element.attrib["d"]
    if tag == "line":
        return (f'M{element.get("x1", "0")} {element.get("y1", "0")} '
                f'L{element.get("x2", "0")} {element.get("y2", "0")}')
    if tag == "circle":
        x, y, r = (float(element.attrib[k]) for k in ("cx", "cy", "r"))
        return f"M{x-r:g} {y:g}a{r:g} {r:g} 0 1 0 {2*r:g} 0a{r:g} {r:g} 0 1 0 {-2*r:g} 0"
    if tag == "rect":
        x, y, w, h = (float(element.get(k, "0")) for k in ("x", "y", "width", "height"))
        rx = min(float(element.get("rx", "0")), w / 2)
        ry = min(float(element.get("ry", str(rx))), h / 2)
        if rx == 0 or ry == 0:
            return f"M{x:g} {y:g}h{w:g}v{h:g}h{-w:g}Z"
        return (f"M{x+rx:g} {y:g}H{x+w-rx:g}a{rx:g} {ry:g} 0 0 1 {rx:g} {ry:g}"
                f"V{y+h-ry:g}a{rx:g} {ry:g} 0 0 1 {-rx:g} {ry:g}"
                f"H{x+rx:g}a{rx:g} {ry:g} 0 0 1 {-rx:g} {-ry:g}"
                f"V{y+ry:g}a{rx:g} {ry:g} 0 0 1 {rx:g} {-ry:g}Z")
    raise ValueError(f"Unsupported SVG element: {tag}")


def convert(source):
    svg = ET.parse(source).getroot()
    assert svg.get("viewBox") == "0 0 24 24", source
    vector = ET.Element("vector", {
        attr("width"): "24dp", attr("height"): "24dp",
        attr("viewportWidth"): "24", attr("viewportHeight"): "24",
    })
    if source.stem in {"arrow-back", "arrow-forward", "chevron-right"}:
        vector.set(attr("autoMirrored"), "true")
    for element in svg:
        ET.SubElement(vector, "path", {
            attr("pathData"): path_data(element),
            attr("fillColor"): "@android:color/transparent",
            attr("strokeColor"): "#FF000000",
            attr("strokeWidth"): element.get("stroke-width", svg.get("stroke-width", "2")),
            attr("strokeLineCap"): element.get("stroke-linecap", svg.get("stroke-linecap", "round")),
            attr("strokeLineJoin"): element.get("stroke-linejoin", svg.get("stroke-linejoin", "round")),
        })
    ET.indent(vector, space="    ")
    target = OUTPUT / f'ic_{source.stem.replace("-", "_")}.xml'
    target.write_text('<?xml version="1.0" encoding="utf-8"?>\n'
                      '<!-- Generated by tools/generate_ui_icons.py from app/artwork/icons. -->\n'
                      + ET.tostring(vector, encoding="unicode") + "\n", encoding="utf-8")


if __name__ == "__main__":
    sources = sorted(SOURCE.glob("*.svg"))
    if not sources:
        raise SystemExit(f"No SVG artwork found in {SOURCE}")
    for source in sources:
        convert(source)
    print(f"Generated {len(sources)} vector drawables.")
